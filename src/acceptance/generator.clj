(ns acceptance.generator
  "APS acceptance entrypoint generator for se-defense: turns parser JSON IR into
  an executable test entry point and a per-feature metadata file. The command
  is 'acceptance-entrypoint-generator <json-ir> <generated-test-output>'."
  (:require [acceptance.json :as json]
            [clojure.string :as str])
  (:import (java.io File)
           (java.security MessageDigest)
           (java.util HashSet)))

(defn slugify
  "Metadata-name mapping: lowercase, runs of non-alphanumerics become one
  hyphen, leading/trailing hyphens trimmed."
  [path]
  (-> (str/lower-case (str path))
      (str/replace #"[^a-z0-9]+" "-")
      (str/replace #"^-+|-+$" "")))

(defn- stem-of
  [ir-path]
  (let [n (.getName (File. (str ir-path)))]
    (if (str/ends-with? n ".json") (subs n 0 (- (count n) 5)) n)))

(defn feature-path-for
  "The source feature path recorded in metadata. ACCEPTANCE_FEATURE_PATH wins;
  otherwise derive features/<stem>.feature from an IR at <dir>/ir/<stem>.json."
  [ir-path]
  (or (not-empty (System/getenv "ACCEPTANCE_FEATURE_PATH"))
      (let [parent (.getName (.getParentFile (File. (str ir-path))))]
        (if (= "ir" parent)
          (str "features/" (stem-of ir-path) ".feature")
          (str ir-path)))))

(defn- sha256-hex
  [s]
  (let [md (MessageDigest/getInstance "SHA-256")
        bytes (.digest md (.getBytes (str s) "UTF-8"))]
    (apply str (map #(format "%02x" (bit-and (int %) 0xff)) bytes))))

(defn test-source
  "Source of the generated test entry point. Loads the given IR (overridable by
  a command-line argument so mutation runs reuse the same entry point) and
  delegates all step behavior to the runtime and project handlers."
  [feature-name default-ir]
  (str "#!/usr/bin/env bb\n"
       ";; Generated by the se-defense acceptance entrypoint generator. Do not edit.\n"
       ";; Feature: " feature-name "\n"
       "(require '[babashka.classpath :as cp])\n"
       "(cp/add-classpath \"src\")\n"
       "(require '[acceptance.runtime :as rt])\n"
       "(require '[acceptance.handlers :as handlers])\n"
       "(require '[acceptance.lua-bridge :as bridge])\n"
       "(def default-ir " (pr-str default-ir) ")\n"
       "(def ir-path (or (first *command-line-args*) default-ir))\n"
       "(let [results (rt/execute-json-ir! ir-path handlers/registry\n"
       "                                  (fn []\n"
       "                                    (let [b (bridge/spawn-bridge!)]\n"
       "                                      {:bridge b\n"
       "                                       :extras (atom {})\n"
       "                                       :dispose! (fn [] ((:close! b)))})))]\n"
       "  (doseq [r results]\n"
       "    (println (case (:status r)\n"
       "               :passed (str \"  ok    \" (:name r))\n"
       "               (str \"  FAIL  \" (:name r) \": \" (:message r)))))\n"
       "  (let [summary (rt/summarize-results results)]\n"
       "    (println (str \"executions=\" (:executions summary)\n"
       "                  \" failed=\" (:failed summary)\n"
       "                  \" infra=\" (:infra summary)))\n"
       "    (when (pos? (+ (:failed summary) (:infra summary)))\n"
       "      (System/exit 1))))\n"))

(defn generate!
  "Writes the generated test entry point and its metadata for one IR file."
  [ir-path out-dir]
  (let [feature-path (feature-path-for ir-path)
        stem (slugify feature-path)
        test-name (str stem "_acceptance_test.clj")
        test-file (str out-dir "/" test-name)
        ir (json/read-json (slurp (str ir-path)))]
    (when-not (map? ir)
      (throw (ex-info "IR is not a feature object" {:ir-path ir-path})))
    (let [meta-dir (File. (str out-dir "/metadata"))]
      (.mkdirs meta-dir))
    (let [src (test-source (get ir "name") (str ir-path))
          test-file-obj (File. test-file)]
      (spit test-file src)
      (java.nio.file.Files/setPosixFilePermissions
       (.toPath test-file-obj)
       (doto (HashSet.)
         (.add java.nio.file.attribute.PosixFilePermission/OWNER_READ)
         (.add java.nio.file.attribute.PosixFilePermission/OWNER_WRITE)
         (.add java.nio.file.attribute.PosixFilePermission/OWNER_EXECUTE)
         (.add java.nio.file.attribute.PosixFilePermission/GROUP_READ)
         (.add java.nio.file.attribute.PosixFilePermission/OTHERS_READ)))
      (let [hash (sha256-hex (slurp test-file))
            meta (json/write-json
                  (array-map :schema_version 1
                             :feature_path feature-path
                             :ir_path (str ir-path)
                             :implementation_hash (str "sha256:" hash)
                             :hash_scope "generated_files"
                             :generated_files [test-name]))]
        (spit (str out-dir "/metadata/" stem ".json") meta)))
    test-file))

(def usage "usage: acceptance-entrypoint-generator <json-ir> <generated-test-output>")

(defn run
  "Command body for testability; returns {:exit code ...}."
  [args]
  (try
    (if (not= 2 (count args))
      (do (binding [*out* *err*] (println usage))
          {:exit 2 :message usage})
      (let [[ir-path out-dir] args]
        (let [test-file (generate! ir-path out-dir)]
          {:exit 0 :test-file test-file})))
    (catch Throwable e
      (binding [*out* *err*] (println (str "error: " (or (ex-message e) (str e)))))
      {:exit 1 :message (ex-message e)})))

